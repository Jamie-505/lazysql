// sqlLiteral quotes a value as a standard SQL string literal.
func sqlLiteral(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

func ansiIdentifier(name string) string {
	return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
}

func backtickIdentifier(name string) string {
	return "`" + strings.ReplaceAll(name, "`", "``") + "`"
}

// TableDDL returns a CREATE statement for the table (or view). MySQL, SQLite
// and ClickHouse report the statement themselves. PostgreSQL and SQL Server
// have no such command, so it is rebuilt from the catalog and is an
// approximation: it is meant for reading, not for replaying.
func TableDDL(ctx context.Context, db Driver, database, table string) (string, error) {
	if table == "" {
		return "", errors.New("table name is required")
	}

	switch db.GetProvider() {
	case DriverMySQL:
		rows, _, err := db.ExecuteQuery(ctx, database, "SHOW CREATE TABLE "+backtickIdentifier(database)+"."+backtickIdentifier(table))
		if err != nil {
			return "", err
		}
		// Columns: Table, Create Table (or View, Create View, ...).
		if data := dataRows(rows); len(data) > 0 && len(data[0]) > 1 {
			return data[0][1], nil
		}
		return "", errors.New("the database returned no definition")

	case DriverClickHouse:
		rows, _, err := db.ExecuteQuery(ctx, database, "SHOW CREATE TABLE "+backtickIdentifier(database)+"."+backtickIdentifier(table))
		if err != nil {
			return "", err
		}
		if text := firstColumnText(rows); text != "" {
			// ClickHouse may return the statement with escaped newlines.
			return strings.ReplaceAll(text, `\n`, "\n"), nil
		}
		return "", errors.New("the database returned no definition")

	case DriverSqlite:
		// The table first, then its indexes and triggers.
		rows, _, err := db.ExecuteQuery(ctx, database,
			"SELECT sql FROM sqlite_master WHERE (name = "+sqlLiteral(table)+" OR tbl_name = "+sqlLiteral(table)+
				") AND sql IS NOT NULL ORDER BY CASE WHEN name = "+sqlLiteral(table)+" THEN 0 ELSE 1 END, name")
		if err != nil {
			return "", err
		}
		var statements []string
		for _, row := range dataRows(rows) {
			if len(row) > 0 && row[0] != "" {
				statements = append(statements, row[0]+";")
			}
		}
		if len(statements) == 0 {
			return "", errors.New("the database returned no definition")
		}
		return strings.Join(statements, "\n\n"), nil

	case DriverPostgres:
		return postgresTableDDL(ctx, db, database, table)

	case DriverMSSQL:
		return mssqlTableDDL(ctx, db, database, table)
	}
	return "", fmt.Errorf("table definitions are not supported for %s", db.GetProvider())
}

const reconstructedNote = "-- Rebuilt from the catalog: for reading, not an exact dump.\n"

func postgresTableDDL(ctx context.Context, db Driver, database, table string) (string, error) {
	schema, name, ok := strings.Cut(table, ".")
	if !ok {
		return "", errors.New("table must be in the format schema.table")
	}
	qualified := ansiIdentifier(schema) + "." + ansiIdentifier(name)
	relation := sqlLiteral(qualified) + "::regclass"

	kindRows, _, err := db.ExecuteQuery(ctx, database, "SELECT relkind FROM pg_class WHERE oid = "+relation)
	if err != nil {
		return "", err
	}
	switch firstColumnText(kindRows) {
	case "v", "m":
		viewRows, _, err := db.ExecuteQuery(ctx, database, "SELECT pg_get_viewdef("+relation+", true)")
		if err != nil {
			return "", err
		}
		keyword := "VIEW"
		if firstColumnText(kindRows) == "m" {
			keyword = "MATERIALIZED VIEW"
		}
		return "CREATE " + keyword + " " + qualified + " AS\n" + firstColumnText(viewRows), nil
	}

	columnRows, _, err := db.ExecuteQuery(ctx, database, `SELECT a.attname, format_type(a.atttypid, a.atttypmod),
       a.attnotnull::text, coalesce(pg_get_expr(d.adbin, d.adrelid), ''), a.attidentity::text
FROM pg_attribute a
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = `+relation+` AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum`)
	if err != nil {
		return "", err
	}
	var definitions []string
	for _, row := range dataRows(columnRows) {
		if len(row) < 5 {
			continue
		}
		definition := "  " + ansiIdentifier(row[0]) + " " + row[1]
		switch row[4] {
		case "a":
			definition += " GENERATED ALWAYS AS IDENTITY"
		case "d":
			definition += " GENERATED BY DEFAULT AS IDENTITY"
		default:
			if row[3] != "" {
				definition += " DEFAULT " + row[3]
			}
		}
		if row[2] == "true" || row[2] == "t" {
			definition += " NOT NULL"
		}
		definitions = append(definitions, definition)
	}
	if len(definitions) == 0 {
		return "", errors.New("the database returned no columns for this table")
	}

	constraintRows, _, err := db.ExecuteQuery(ctx, database, `SELECT conname, pg_get_constraintdef(oid)
FROM pg_constraint
WHERE conrelid = `+relation+`
ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'f' THEN 2 ELSE 3 END, conname`)
	if err != nil {
		return "", err
	}
	for _, row := range dataRows(constraintRows) {
		if len(row) >= 2 {
			definitions = append(definitions, "  CONSTRAINT "+ansiIdentifier(row[0])+" "+row[1])
		}
	}

	var out strings.Builder
	out.WriteString(reconstructedNote)
	out.WriteString("CREATE TABLE " + qualified + " (\n" + strings.Join(definitions, ",\n") + "\n);")

	indexRows, _, err := db.ExecuteQuery(ctx, database, `SELECT indexdef
FROM pg_indexes
WHERE schemaname = `+sqlLiteral(schema)+` AND tablename = `+sqlLiteral(name)+`
  AND indexname NOT IN (SELECT conname FROM pg_constraint WHERE conrelid = `+relation+`)
ORDER BY indexname`)
	if err != nil {
		return "", err
	}
	for _, row := range dataRows(indexRows) {
		if len(row) > 0 && row[0] != "" {
			out.WriteString("\n\n" + row[0] + ";")
		}
	}
	return out.String(), nil
}

// mssqlColumnType renders a sys.columns type with its length or precision.
func mssqlColumnType(typeName, maxLength, precision, scale string) string {
	length, _ := strconv.Atoi(maxLength)
	switch strings.ToLower(typeName) {
	case "nvarchar", "nchar":
		if length == -1 {
			return typeName + "(MAX)"
		}
		return fmt.Sprintf("%s(%d)", typeName, length/2)
	case "varchar", "char", "varbinary", "binary":
		if length == -1 {
			return typeName + "(MAX)"
		}
		return fmt.Sprintf("%s(%d)", typeName, length)
	case "decimal", "numeric":
		return fmt.Sprintf("%s(%s, %s)", typeName, precision, scale)
	case "datetime2", "time", "datetimeoffset":
		return fmt.Sprintf("%s(%s)", typeName, scale)
	}
	return typeName
}

func mssqlTableDDL(ctx context.Context, db Driver, database, table string) (string, error) {
	schema, name, qualified, err := splitMSSQLTableReference(table)
	if err != nil {
		return "", err
	}
	reference := quoteMSSQLIdentifier(name)
	if qualified {
		reference = quoteMSSQLIdentifier(schema) + "." + reference
	}
	objectID := "OBJECT_ID(N" + sqlLiteral(reference) + ")"

	viewRows, _, err := db.ExecuteQuery(ctx, database, "SELECT definition FROM sys.sql_modules WHERE object_id = "+objectID)
	if err != nil {
		return "", err
	}
	if definition := firstColumnText(viewRows); definition != "" {
		return definition, nil
	}

	columnRows, _, err := db.ExecuteQuery(ctx, database, `SELECT c.name, t.name, c.max_length, c.precision, c.scale,
       c.is_nullable, c.is_identity, COALESCE(dc.definition, '')
FROM sys.columns c
JOIN sys.types t ON t.user_type_id = c.user_type_id
LEFT JOIN sys.default_constraints dc ON dc.object_id = c.default_object_id
WHERE c.object_id = `+objectID+`
ORDER BY c.column_id`)
	if err != nil {
		return "", err
	}
	isTrue := func(value string) bool { return value == "1" || strings.EqualFold(value, "true") }
	var definitions []string
	for _, row := range dataRows(columnRows) {
		if len(row) < 8 {
			continue
		}
		definition := "  " + quoteMSSQLIdentifier(row[0]) + " " + mssqlColumnType(row[1], row[2], row[3], row[4])
		if isTrue(row[6]) {
			definition += " IDENTITY"
		}
		if row[7] != "" {
			definition += " DEFAULT " + row[7]
		}
		if !isTrue(row[5]) {
			definition += " NOT NULL"
		}
		definitions = append(definitions, definition)
	}
	if len(definitions) == 0 {
		return "", errors.New("the database returned no columns for this table")
	}

	keyRows, _, err := db.ExecuteQuery(ctx, database, `SELECT kc.name, col.name
FROM sys.key_constraints kc
JOIN sys.index_columns ic ON ic.object_id = kc.parent_object_id AND ic.index_id = kc.unique_index_id
JOIN sys.columns col ON col.object_id = ic.object_id AND col.column_id = ic.column_id
WHERE kc.parent_object_id = `+objectID+` AND kc.type = 'PK'
ORDER BY ic.key_ordinal`)
	if err != nil {
		return "", err
	}
	var keyName string
	var keyColumns []string
	for _, row := range dataRows(keyRows) {
		if len(row) >= 2 {
			keyName = row[0]
			keyColumns = append(keyColumns, quoteMSSQLIdentifier(row[1]))
		}
	}
	if len(keyColumns) > 0 {
		definitions = append(definitions, "  CONSTRAINT "+quoteMSSQLIdentifier(keyName)+" PRIMARY KEY ("+strings.Join(keyColumns, ", ")+")")
	}

	return reconstructedNote +
		"-- Foreign keys, other constraints and indexes are on tabs 3 to 5.\n" +
		"CREATE TABLE " + reference + " (\n" + strings.Join(definitions, ",\n") + "\n);", nil
}

// ServerInfoItem is one labelled fact about the connected server.
type ServerInfoItem struct {
	Label string
	Value string
}

// ServerInfo returns version and session facts for the connected server.
func ServerInfo(ctx context.Context, db Driver) ([]ServerInfoItem, error) {
	var labels []string
	var query string
	switch db.GetProvider() {
	case DriverPostgres:
		labels = []string{"Version", "User", "Database", "Database size", "Encoding", "Uptime"}
		query = `SELECT version(), current_user, current_database(),
       pg_size_pretty(pg_database_size(current_database())),
       current_setting('server_encoding'),
       date_trunc('second', now() - pg_postmaster_start_time())::text`
	case DriverMySQL:
		labels = []string{"Version", "User", "Database", "Character set", "Host"}
		query = "SELECT VERSION(), CURRENT_USER(), COALESCE(DATABASE(), ''), @@character_set_server, @@hostname"
	case DriverSqlite:
		labels = []string{"Version", "Encoding"}
		query = "SELECT sqlite_version(), (SELECT encoding FROM pragma_encoding)"
	case DriverMSSQL:
		labels = []string{"Version", "User", "Database", "Server"}
		query = "SELECT @@VERSION, SUSER_SNAME(), DB_NAME(), @@SERVERNAME"
	case DriverClickHouse:
		labels = []string{"Version", "User", "Database", "Host", "Uptime (s)"}
		query = "SELECT version(), currentUser(), currentDatabase(), hostName(), toString(uptime())"
	default:
		return nil, fmt.Errorf("server information is not supported for %s", db.GetProvider())
	}

	rows, _, err := db.ExecuteQuery(ctx, "", query)
	if err != nil {
		return nil, err
	}
	data := dataRows(rows)
	if len(data) == 0 {
		return nil, errors.New("the database returned no server information")
	}

	items := []ServerInfoItem{{Label: "Engine", Value: db.GetProvider()}}
	for i, label := range labels {
		if i >= len(data[0]) {
			break
		}
		// SQL Server reports a multi-line banner; the first line is the version.
		value, _, _ := strings.Cut(strings.TrimSpace(data[0][i]), "\n")
		items = append(items, ServerInfoItem{Label: label, Value: strings.TrimSpace(value)})
	}
	return items, nil
}
